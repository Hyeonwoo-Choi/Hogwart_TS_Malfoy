/** 활동·장소·반복 횟수에 맞는 활동 장면을 고른다. 이벤트가 이어질 때는 항상 짧은 장면(s). */
export function activitySceneFor(actId: string, count: number, hasEvent: boolean): string {
  const pick = (v: 'a' | 'b' | 's') => `act_${actId}_${v}`
  const id = hasEvent ? pick('s') : count === 0 ? pick('a') : count === 1 ? pick('b') : pick(count % 2 === 0 ? 's' : 'b')
  return ACTIVITY_SCENES[id] ? id : 'act_generic_s'
}
